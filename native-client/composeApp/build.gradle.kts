// Read from gradle.properties, env var, or command-line (-P) override
val defaultServerUrl: String = findProperty("DEFAULT_SERVER_URL") as? String
    ?: System.getenv("DEFAULT_SERVER_URL")
    ?: "https://obsidian.tuong.me"

// Generate a BuildConfig object visible to commonMain so both Android and desktop
// can read the value without platform-specific code.
val generateBuildConfig by tasks.registering {
    val outputDir = layout.buildDirectory.dir("generated/buildconfig")
    outputs.dir(outputDir)
    doLast {
        val dir = outputDir.get().asFile.resolve("com/xnohat/webobsidian")
        dir.mkdirs()
        dir.resolve("BuildConfig.kt").writeText(
            """
            |package com.xnohat.webobsidian
            |
            |/** Auto-generated by Gradle — do not edit. */
            |object BuildConfig {
            |    const val DEFAULT_SERVER_URL: String = "${defaultServerUrl.replace("\"", "\\\"")}"
            |}
            """.trimMargin()
        )
    }
}

kotlin.sourceSets.getByName("commonMain") {
    kotlin.srcDir(generateBuildConfig.map { layout.buildDirectory.dir("generated/buildconfig") })
}

tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
    dependsOn(generateBuildConfig)
}

